/// <summary>
/// The strangler of SemanticModernization.md §7, generated with the code into &lt;base&gt;.batch.strangler: a batch step
/// is a port (its datasets in, its return code out) with two implementations, the legacy job (a process: the GnuCOBOL
/// executable, or a faithful Java job, its datasets bound by DD_NAME as GnuCOBOL resolves ASSIGN names) and the
/// modern code (the generated batch step in the same JVM). LEGACY runs the first, MODERN the second, SHADOW both on the
/// same input: the legacy outputs are the step's (the system of record), the modern ones are compared record by record
/// and every difference is reported with the request that produced it (shadow-report.json). GN4 runs SHADOW over the
/// scenarios and passes with no difference.
/// </summary>
static class Strangler
{
    public static IEnumerable<(string Name, string Text)> Files(AppModel app)
    {
        var pkg = app.AppPackage + ".strangler";
        string Fill(string t) => t.Replace("PKG", pkg).Replace("APP", app.AppPackage);
        yield return ("StepPort.java", Fill(StepPort));
        yield return ("ModernStep.java", Fill(ModernStep));
        yield return ("LegacyStep.java", Fill(LegacyStep));
        yield return ("Shadow.java", Fill(Shadow));
        yield return ("Strangler.java", Fill(Main));
        yield return ("Steps.java", StepsText(app, pkg));
    }

    /// <summary>The batch steps: their datasets (from the OPEN statements), output record lengths and layouts (the records written).</summary>
    static string StepsText(AppModel app, string pkg)
    {
        var sb = new StringBuilder();
        sb.Append("package ").Append(pkg).Append(";\n\n");
        foreach (var ap in app.Programs.Where(p => p.IsStep).OrderBy(p => p.ClassName, StringComparer.Ordinal))
            sb.Append("import ").Append(app.AppPackage).Append('.').Append(ap.ClassName).Append(";\n");
        sb.Append("import java.util.LinkedHashMap;\nimport java.util.List;\nimport java.util.Map;\nimport java.util.Set;\nimport java.util.function.IntSupplier;\n\n");
        sb.Append("/**\n * The batch steps of the estate (legacy programs ");
        sb.Append(string.Join(", ", app.Programs.Where(p => p.IsStep).Select(p => p.P.Id)));
        sb.Append("): their datasets by DD name, the modern implementation, the\n * layouts of the records they write. Generated by MlCpu.Modernize from the COBOL: do not edit, regenerate.\n */\n");
        sb.Append("public final class Steps {\n    private Steps() {}\n\n");
        sb.Append("    /** A field of an output record: its legacy name, 0-based offset and length. */\n");
        sb.Append("    public record Field(String name, int offset, int length) {}\n\n");
        sb.Append("    /** A step: the legacy program's name, the modern step, its inputs and outputs with their record lengths, the indexed inputs, the outputs' layouts. */\n");
        sb.Append("    public record Step(String name, IntSupplier modern, Map<String, Integer> inputs, Set<String> indexed, Map<String, Integer> outputs, Map<String, List<Field>> layouts) {}\n\n");
        sb.Append("    /** The steps by legacy program name. */\n");
        sb.Append("    public static final Map<String, Step> ALL = new LinkedHashMap<>();\n\n");
        sb.Append("    static {\n");
        foreach (var ap in app.Programs.Where(p => p.IsStep))
        {
            var (inputs, outputs) = Datasets(ap);
            var layouts = new List<string>();
            foreach (var (f, _) in outputs)
            {
                var fields = Layout(ap, f).Select(x => $"new Field(\"{x.Name}\", {x.Offset}, {x.Length})");
                layouts.Add($"\"{f.Assign}\", List.of({string.Join(", ", fields)})");
            }
            // the legacy SELECT names by DD name: the runtime-compatibility profile's diagnostics name the files with them
            var selects = string.Join(", ", ap.P.Model.Files.Where(f => !string.IsNullOrEmpty(f.Assign)).Select(f => $"Map.entry(\"{f.Assign}\", \"{f.Name}\")"));
            sb.Append($"        ALL.put(\"{ap.P.Id}\", new Step(\"{ap.P.Id}\", () -> {{ {app.PlatformPackage}.Datasets.legacyFiles(Map.ofEntries({selects})); return new {ap.ClassName}().run(); }},\n");
            sb.Append($"            Map.of({string.Join(", ", inputs.Select(f => $"\"{f.Assign}\", {f.MaxRecord}"))}),\n");
            sb.Append($"            Set.of({string.Join(", ", inputs.Where(f => f.Organization == "INDEXED").Select(f => $"\"{f.Assign}\""))}),\n");
            sb.Append($"            Map.of({string.Join(", ", outputs.Select(o => $"\"{o.F.Assign}\", {o.F.MaxRecord}"))}),\n");
            sb.Append($"            Map.of({string.Join(",\n                ", layouts)})));\n");
        }
        sb.Append("    }\n}\n");
        return sb.ToString();
    }

    /// <summary>The files a program opens for input and for output, in the order it opens them.</summary>
    static (List<FileDecl> Inputs, List<(FileDecl F, string Mode)> Outputs) Datasets(AppProgram ap)
    {
        var inputs = new List<FileDecl>();
        var outputs = new List<(FileDecl, string)>();
        foreach (var s in ap.Classic.SelectMany(p => Model.Deep(p.Statements)).Where(s => s.Verb == "OPEN"))
            foreach (var fn in s.L?.GetValueOrDefault("files") ?? [])
            {
                var f = ap.P.Model.Files.FirstOrDefault(x => x.Name.Equals(fn.V, StringComparison.OrdinalIgnoreCase));
                if (f is null) continue;
                var mode = (fn.Op ?? "INPUT").ToUpperInvariant();
                if (mode == "INPUT") { if (!inputs.Contains(f)) inputs.Add(f); }
                else if (!outputs.Any(o => o.Item1 == f)) outputs.Add((f, mode));
            }
        return (inputs, outputs);
    }

    /// <summary>The fields of the records a program writes to a file (WRITE ... FROM the record, else the FD record).</summary>
    static List<(string Name, int Offset, int Length)> Layout(AppProgram ap, FileDecl f)
    {
        // of the records written to the file (WRITE ... FROM), the one with the most fields: the layout the others fill
        DataItem? rec = null;
        foreach (var s in ap.Classic.SelectMany(p => Model.Deep(p.Statements)).Where(s => s.Verb == "WRITE"))
        {
            var r = s.Get("record") is { Id: int rid } && ap.P.ItemsById.TryGetValue(rid, out var ri) ? ri : null;
            if (r is null || !f.Records.Any(x => x == r || x.Name == r.Name)) continue;
            var from = s.Get("from") is { Id: int fid } && ap.P.ItemsById.TryGetValue(fid, out var fi) ? fi : r;
            if (rec is null || Fields(from) > Fields(rec)) rec = from;
        }
        static int Fields(DataItem d) => AppModel.Leaves(d).Count(l => !l.IsFiller && l.Dims.Count == d.Dims.Count);
        rec ??= f.Records.FirstOrDefault();
        if (rec is null) return [];
        // a table element written (WRITE ... FROM OUT-ENTRY (K)): its fields relative to the element, no nested tables
        return AppModel.Leaves(rec).Where(l => !l.IsFiller && l.Dims.Count == rec.Dims.Count).Select(l => (l.Name, l.Offset - rec.Offset, l.Length)).ToList();
    }

