    const string ModernStep = """
package PKG;

import APP.platform.Datasets;
import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.Map;
import java.util.function.IntSupplier;

/**
 * The modern implementation of a step: the generated batch step, run in this JVM over the given datasets. Traced, every
 * record it writes carries the request it belongs to; captured, its DISPLAY output is kept for comparison.
 * Generated by MlCpu.Modernize.
 */
public final class ModernStep implements StepPort {
    private final IntSupplier step;
    private final boolean trace;
    private final boolean capture;
    private String sysout = "";

    /** The step (a Steps entry's modern()), traced or not, its DISPLAY output captured or printed. */
    public ModernStep(IntSupplier step, boolean trace, boolean capture) {
        this.step = step;
        this.trace = trace;
        this.capture = capture;
    }

    /** Runs the step once (the domain keeps static state: one run per JVM). */
    @Override
    public int run(Map<String, Path> datasets) {
        Datasets.bind(datasets, trace);
        // the runtime-compatibility profile is the parity harness's choice (-Dmlcpu.runtimeProfile); none: no diagnostics
        if (!capture) {
            try {
                return step.getAsInt();
            } finally {
                Datasets.terminate().forEach(System.out::println);
            }
        }
        PrintStream out = System.out;
        ByteArrayOutputStream buffer = new ByteArrayOutputStream();
        System.setOut(new PrintStream(buffer, true, StandardCharsets.ISO_8859_1));
        try {
            return step.getAsInt();
        } finally {
            // the end of the run unit: the profile's runtime diagnostics for files left open, every file released
            Datasets.terminate().forEach(System.out::println);
            System.out.flush();
            System.setOut(out);
            sysout = buffer.toString(StandardCharsets.ISO_8859_1);
        }
    }

    /** The DISPLAY output of the run (captured runs). */
    public String sysout() {
        return sysout;
    }
}
""";

    const string LegacyStep = """
package PKG;

import APP.platform.Datasets;
import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * The legacy implementation of a step: the legacy job (the GnuCOBOL executable of the program, or a faithful Java job)
 * run as a process over its datasets in the legacy runtime's formats, bound by DD_NAME environment variables as GnuCOBOL
 * resolves ASSIGN names. A sequential input becomes a fixed-record image (the mainframe's RECFM F); an indexed input is
 * loaded first by its loader (-Dlegacy.load.DD=command, which reads DD SEQFILE and writes DD KSDSFILE, as CobolBdm's
 * generated LOAD programs do). Used in LEGACY and SHADOW modes; deleted with the legacy program at retirement.
 * Generated by MlCpu.Modernize.
 */
public final class LegacyStep implements StepPort {
    private final Steps.Step step;
    private final List<String> command;
    private final String runtimePath;
    private final Path work;
    private final Path sysout;

    /** The step, its command (program and arguments), a directory put first on PATH (the COBOL runtime) or null, a work directory. */
    public LegacyStep(Steps.Step step, List<String> command, String runtimePath, Path work) {
        this.step = step;
        this.command = command;
        this.runtimePath = runtimePath;
        this.work = work;
        this.sysout = work.resolve(step.name() + ".legacy.sysout");
    }

    /** A legacy command: the system property legacy.KEY, else the environment variable LEGACY_KEY (space-separated). */
    public static List<String> commandOf(String key) {
        String c = System.getProperty("legacy." + key);
        if (c == null) c = System.getenv("LEGACY_" + key.replace('.', '_'));
        if (c == null || c.isBlank()) throw new IllegalArgumentException("no legacy command: -Dlegacy." + key + "=<command>");
        return new ArrayList<>(Arrays.asList(c.trim().split("\\s+")));
    }

    /** Prepares the inputs in the legacy formats, then runs the legacy job; its exit code is the step's return code. */
    @Override
    public int run(Map<String, Path> datasets) throws IOException, InterruptedException {
        Map<String, Path> bound = new LinkedHashMap<>(datasets);
        Files.deleteIfExists(sysout);
        for (Map.Entry<String, Integer> in : step.inputs().entrySet()) {
            String dd = in.getKey();
            Path src = datasets.get(dd);
            if (src == null || !Files.exists(src)) continue;
            ByteArrayOutputStream image = new ByteArrayOutputStream();
            for (byte[] r : Datasets.records(src, in.getValue())) image.write(r);
            Path fixed = work.resolve(step.name() + "." + dd + ".legacy");
            Files.write(fixed, image.toByteArray());
            if (step.indexed().contains(dd)) {
                Path ksds = work.resolve(step.name() + "." + dd + ".legacy.bdb");
                Files.deleteIfExists(ksds);
                int rc = process(commandOf("load." + dd), Map.of("SEQFILE", fixed, "KSDSFILE", ksds));
                if (rc != 0) throw new IllegalStateException("loading the indexed input " + dd + ": return code " + rc);
                bound.put(dd, ksds);
            } else {
                bound.put(dd, fixed);
            }
        }
        return process(command, bound);
    }

    int process(List<String> cmd, Map<String, Path> dds) throws IOException, InterruptedException {
        ProcessBuilder pb = new ProcessBuilder(cmd);
        Map<String, String> env = pb.environment();
        for (Map.Entry<String, Path> e : dds.entrySet()) env.put("DD_" + e.getKey(), e.getValue().toAbsolutePath().toString());
        if (runtimePath != null && !runtimePath.isBlank()) env.put("PATH", runtimePath + File.pathSeparator + env.getOrDefault("PATH", ""));
        pb.redirectErrorStream(true);
        pb.redirectOutput(ProcessBuilder.Redirect.appendTo(sysout.toFile()));
        return pb.start().waitFor();
    }

    /** The file the legacy job's output went to. */
    public Path sysout() {
        return sysout;
    }
}
""";

    const string Shadow = """
package PKG;

import APP.platform.Datasets;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;

/**
 * SHADOW: the legacy job and the modern step on the same input. The legacy outputs are the step's (the system of
 * record); the modern ones go next to them (NAME.modern) and are compared record by record, realigned after an
 * inserted or a missing record. Every difference is reported with the request that produced it (the modern step's
 * trace: the requests read before the record was written), the dataset, the records and, for a changed record, the
 * first differing field. Generated by MlCpu.Modernize.
 */
public final class Shadow {
    private Shadow() {}

    /** Records looked ahead to realign two outputs after an inserted or a missing record. */
    static final int WINDOW = 400;
    /** Differences listed in the report (all are counted). */
    static final int LISTED = 1000;

    /** One difference: its request, kind (different, legacy-only, modern-only), dataset, records (1-based) and field. */
    record Difference(int request, String kind, String dataset, int legacyRecord, int modernRecord, int offset, String field, String legacy, String modern) {}

    /** Runs the step in SHADOW mode; writes the report; returns the legacy return code (the system of record's). */
    public static int run(Steps.Step step, Map<String, Path> datasets, LegacyStep legacy, Path report) throws Exception {
        int legacyRc = legacy.run(datasets);
        Map<String, Path> modernDatasets = new LinkedHashMap<>(datasets);
        for (String out : step.outputs().keySet()) modernDatasets.put(out, Path.of(datasets.get(out) + ".modern"));
        ModernStep modern = new ModernStep(step.modern(), true, true);
        int modernRc = modern.run(modernDatasets);
        Map<String, List<Integer>> trace = Datasets.trace();
        int requests = Datasets.requests();
        List<Difference> diffs = new ArrayList<>();
        int total = 0;
        StringBuilder sets = new StringBuilder();
        for (Map.Entry<String, Integer> out : step.outputs().entrySet()) {
            String dd = out.getKey();
            List<byte[]> l = read(datasets.get(dd), out.getValue());
            List<byte[]> m = read(modernDatasets.get(dd), out.getValue());
            List<Integer> req = trace.getOrDefault(dd, List.of());
            int before = total;
            total += compare(dd, l, m, req, step.layouts().getOrDefault(dd, List.of()), diffs);
            if (sets.length() > 0) sets.append(",\n");
            sets.append("    \"").append(json(dd)).append("\": {\"legacyRecords\": ").append(l.size()).append(", \"modernRecords\": ").append(m.size())
                .append(", \"differences\": ").append(total - before).append('}');
        }
        if (legacyRc != modernRc) total++;
        TreeSet<Integer> requestsWithDifferences = new TreeSet<>();
        for (Difference d : diffs) requestsWithDifferences.add(d.request());
        // DISPLAY output: the modern step's lines are the legacy job's, in order; the legacy runtime's own (J3S heap
        // statistics) have no counterpart
        List<String> legacyOut = lines(Files.exists(legacy.sysout()) ? Files.readString(legacy.sysout(), StandardCharsets.ISO_8859_1) : "");
        List<String> modernOut = lines(modern.sysout());
        Files.writeString(Path.of(legacy.sysout().toString().replace(".legacy.sysout", ".modern.sysout")), modern.sysout(), StandardCharsets.ISO_8859_1);
        int k = 0;
        for (String line : legacyOut) if (k < modernOut.size() && line.equals(modernOut.get(k))) k++;
        boolean sysoutContained = k == modernOut.size();
        StringBuilder sb = new StringBuilder();
        sb.append("{\n  \"step\": \"").append(json(step.name())).append("\",\n  \"mode\": \"SHADOW\",\n");
        sb.append("  \"runtimeProfile\": \"").append(String.valueOf(System.getProperty(Datasets.PROFILE_PROPERTY))).append("\", \"runtimeProfileSha256\": \"").append(Datasets.PROFILE_SHA256).append("\",\n");
        sb.append("  \"legacyReturnCode\": ").append(legacyRc).append(",\n  \"modernReturnCode\": ").append(modernRc).append(",\n");
        sb.append("  \"requests\": ").append(requests).append(",\n");
        sb.append("  \"requestsWithDifferences\": ").append(requestsWithDifferences.size()).append(",\n");
        sb.append("  \"differences\": ").append(total).append(",\n");
        sb.append("  \"sysout\": {\"modernLines\": ").append(modernOut.size()).append(", \"inLegacyInOrder\": ").append(sysoutContained)
            .append(", \"legacyOnlyLines\": ").append(legacyOut.size() - k).append("},\n");
        sb.append("  \"datasets\": {\n").append(sets).append("\n  },\n");
        sb.append("  \"listed\": [");
        for (int i = 0; i < diffs.size(); i++) {
            Difference d = diffs.get(i);
            sb.append(i == 0 ? "\n" : ",\n").append("    {\"request\": ").append(d.request()).append(", \"kind\": \"").append(d.kind())
                .append("\", \"dataset\": \"").append(json(d.dataset())).append("\", \"legacyRecord\": ").append(d.legacyRecord())
                .append(", \"modernRecord\": ").append(d.modernRecord()).append(", \"offset\": ").append(d.offset())
                .append(", \"field\": ").append(d.field() == null ? "null" : "\"" + json(d.field()) + "\"")
                .append(", \"legacy\": \"").append(json(d.legacy())).append("\", \"modern\": \"").append(json(d.modern())).append("\"}");
        }
        sb.append(diffs.isEmpty() ? "]\n}\n" : "\n  ]\n}\n");
        Files.writeString(report, sb.toString(), StandardCharsets.UTF_8);
        System.err.println("SHADOW " + step.name() + ": " + requests + " requests, " + requestsWithDifferences.size() + " with differences, "
            + total + " differences, return codes " + legacyRc + "/" + modernRc + ", sysout " + (sysoutContained ? "in the legacy's" : "different")
            + " (" + (legacyOut.size() - k) + " legacy-only lines)");
        return legacyRc;
    }

    /** Compares one output; adds its differences (up to LISTED in all) and returns how many there are. */
    static int compare(String dd, List<byte[]> l, List<byte[]> m, List<Integer> req, List<Steps.Field> layout, List<Difference> out) {
        int i = 0, j = 0, n = 0;
        while (i < l.size() || j < m.size()) {
            if (i < l.size() && j < m.size() && Arrays.equals(l.get(i), m.get(j))) { i++; j++; continue; }
            int[] r = realign(l, i, m, j);
            int a = r == null ? l.size() - i : r[0];
            int b = r == null ? m.size() - j : r[1];
            int pairs = Math.min(a, b);
            for (int k = 0; k < Math.max(a, b); k++) {
                n++;
                if (out.size() >= LISTED) continue;
                int li = k < a ? i + k : -1, mj = k < b ? j + k : -1;
                int request = mj >= 0 && mj < req.size() ? req.get(mj) : j > 0 && j - 1 < req.size() ? req.get(j - 1) : 0;
                if (k < pairs) out.add(changed(dd, request, l.get(li), m.get(mj), li + 1, mj + 1, layout));
                else if (li >= 0) out.add(new Difference(request, "legacy-only", dd, li + 1, 0, 0, null, text(l.get(li), 0, Math.min(80, l.get(li).length)), ""));
                else out.add(new Difference(request, "modern-only", dd, 0, mj + 1, 0, null, "", text(m.get(mj), 0, Math.min(80, m.get(mj).length))));
            }
            i += a;
            j += b;
        }
        return n;
    }

    /** The nearest realignment (a records of the legacy output and b of the modern one skipped), or null within WINDOW. */
    static int[] realign(List<byte[]> l, int i, List<byte[]> m, int j) {
        for (int d = 1; d <= WINDOW; d++)
            for (int a = 0; a <= d; a++) {
                int b = d - a;
                if (i + a < l.size() && j + b < m.size() && Arrays.equals(l.get(i + a), m.get(j + b))
                    && (i + a + 1 >= l.size() || j + b + 1 >= m.size() || Arrays.equals(l.get(i + a + 1), m.get(j + b + 1))))
                    return new int[] { a, b };
            }
        return null;
    }

    static Difference changed(String dd, int request, byte[] l, byte[] m, int li, int mj, List<Steps.Field> layout) {
        int off = 0;
        while (off < Math.min(l.length, m.length) && l[off] == m[off]) off++;
        // the narrowest field at the first differing byte; a REDEFINES gives several, named after it (narrowest first)
        List<Steps.Field> at = new ArrayList<>();
        for (Steps.Field f : layout) if (off >= f.offset() && off < f.offset() + f.length()) at.add(f);
        at.sort((x, y) -> Integer.compare(x.length(), y.length()));
        if (!at.isEmpty()) {
            Steps.Field f = at.get(0);
            String name = f.name();
            if (at.size() > 1) name += " (or " + String.join(", ", at.subList(1, at.size()).stream().map(Steps.Field::name).toList()) + ")";
            return new Difference(request, "different", dd, li, mj, off, name, text(l, f.offset(), f.length()), text(m, f.offset(), f.length()));
        }
        int end = Math.min(off + 20, Math.min(l.length, m.length));
        return new Difference(request, "different", dd, li, mj, off, null, text(l, off, end - off), text(m, off, end - off));
    }

    static List<byte[]> read(Path p, int lrecl) {
        try {
            return Files.exists(p) ? Datasets.records(p, lrecl) : List.of();
        } catch (IOException e) {
            return List.of();
        }
    }

    static String text(byte[] r, int off, int len) {
        return new String(r, off, Math.max(0, Math.min(len, r.length - off)), StandardCharsets.ISO_8859_1);
    }

    /** DISPLAY output line by line: line ends, trailing spaces and empty lines do not count. */
    static List<String> lines(String s) {
        List<String> out = new ArrayList<>();
        for (String line : s.replace("\r\n", "\n").split("\n")) if (!line.isBlank()) out.add(line.stripTrailing());
        return out;
    }

    static String json(String s) {
        StringBuilder sb = new StringBuilder();
        for (char c : s.toCharArray()) {
            if (c == '"' || c == '\\') sb.append('\\').append(c);
            else if (c < 0x20 || c > 0x7e) sb.append(String.format("\\u%04x", (int) c));
            else sb.append(c);
        }
        return sb.toString();
    }
}
""";

    const string Main = """
package PKG;

import APP.platform.Datasets;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * The strangler of the estate's batch steps (SemanticModernization.md §7): runs a step LEGACY (the legacy job), MODERN
 * (the generated code) or SHADOW (both on the same input, compared per request in shadow-report.json; the legacy
 * outputs stay the step's). Usage: Strangler STEP MODE [DD=path ...]. A DD not given is found as the step finds it
 * (-Ddd.NAME, DD_NAME, NAME). The legacy job: -Dlegacy.STEP="command" (or LEGACY_STEP), -Dlegacy.path=its runtime
 * directory; -Dshadow.report=path (default shadow-report.json). Generated by MlCpu.Modernize.
 */
public final class Strangler {
    private Strangler() {}

    /** The command line (see the class); exits with the system of record's return code. */
    public static void main(String[] args) throws Exception {
        if (args.length < 2 || !Steps.ALL.containsKey(args[0].toUpperCase())) {
            System.err.println("usage: Strangler STEP LEGACY|SHADOW|MODERN [DD=path ...]; steps " + Steps.ALL.keySet());
