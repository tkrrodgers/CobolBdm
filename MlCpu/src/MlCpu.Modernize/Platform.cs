namespace MlCpu.Modernize;

/// <summary>
/// The small runtime the generated application layer uses (SemanticModernization.md, ports and adapters): codecs of
/// fixed-width record images, the datasets of a batch step, the legacy site of an exception (the reject mapping), and
/// the abend. Emitted into the output project in package &lt;base&gt;.batch.platform; generated, never edited.
/// </summary>
static class Platform
{
    public static IEnumerable<(string Name, string Text)> Files(string pkg, bool displayedAbends = false, bool prefaced = false)
    {
        yield return ("Records.java", Records.Replace("PKG", pkg));
        yield return ("Datasets.java", Datasets.Replace("PKG", pkg));
        yield return ("LegacySites.java", LegacySites.Replace("PKG", pkg));
        // an abend routine that reports the abend (DISPLAY ... ABENDING, then CEE3ABD): the abend carries its lines
        var abend = prefaced ? Prefaced(Abend) : Abend;
        yield return ("Abend.java", (displayedAbends ? abend.Replace("    private Abend(int code, String message, String routine, String site, List<String> display) {", AbendDisplayed) : abend).Replace("PKG", pkg));
        yield return ("DatasetException.java", DatasetException.Replace("PKG", pkg));
        yield return ("RunReport.java", RunReport.Replace("PKG", pkg));
    }

    /// <summary>A step's report: its lines as RunReport writes them, its edited values with the legacy PICTUREs.</summary>
    public static string ReportFormatter(string pkg, string cls, string program, List<(string Method, string Picture, string Legacy)> edits)
    {
        var sb = new System.Text.StringBuilder();
        sb.Append("package ").Append(pkg).Append(";\n\n");
        sb.Append($"/**\n * The run report of {program}: its lines, and its numbers edited as the legacy report prints them (the PICTUREs of its\n");
        sb.Append(" * edited items), so the report keeps the legacy text character for character.\n * <p>Generated by MlCpu.Modernize: do not edit, regenerate.\n */\n");
        sb.Append($"public class {cls} extends RunReport {{\n");
        for (int i = 0; i < edits.Count; i++)
        {
            var (method, pic, legacy) = edits[i];
            sb.Append($"    /** A number as {legacy} (PIC {pic}) prints it. */\n");
            sb.Append($"    public String {method}(long value) {{\n");
            sb.Append($"        return Records.edit(value, \"{pic.Replace("\\", "\\\\").Replace("\"", "\\\"")}\");\n");
            sb.Append("    }\n");
            if (i < edits.Count - 1) sb.Append('\n');
        }
        sb.Append("}\n");
        return sb.ToString();
    }

