package PKG;

import java.math.BigDecimal;
import java.math.BigInteger;

/**
 * Signed zoned decimals with the sign over the last digit (PIC S9(n) DISPLAY, no SIGN SEPARATE), as GnuCOBOL stores them
 * with -fsign=EBCDIC: the last digit is '{', 'A'..'I' when the value is positive, '}', 'J'..'R' when it is negative;
 * any other byte is a positive digit (its low four bits). A store keeps the low-order digits and the value's sign, so a
 * negative value truncated to zero is stored negative (and reads as zero).
 */
public final class ZonedDecimal {
    private ZonedDecimal() {}

    /** The value of the len-byte field at off, with scale decimal places. */
    public static BigDecimal get(byte[] r, int off, int len, int scale) {
        long v = 0;
        for (int i = 0; i < len - 1; i++) v = v * 10 + digit(r[off + i] & 0xFF);
        int last = r[off + len - 1] & 0xFF;
        boolean negative = last == '}' || last >= 'J' && last <= 'R';
        int d = last == '{' || last == '}' ? 0 : last >= 'A' && last <= 'I' ? last - 'A' + 1 : last >= 'J' && last <= 'R' ? last - 'J' + 1 : digit(last);
        BigDecimal value = BigDecimal.valueOf(v * 10 + d, scale);
        return negative ? value.negate() : value;
    }

    /** Stores the value's low-order digits at scale decimal places (truncated) with its sign over the last digit. */
    public static void put(byte[] r, int off, int len, int scale, BigDecimal value) {
        BigInteger unscaled = value.movePointRight(scale).toBigInteger().abs();
        String digits = unscaled.toString();
        if (digits.length() > len) digits = digits.substring(digits.length() - len);
        digits = "0".repeat(len - digits.length()) + digits;
        for (int i = 0; i < len - 1; i++) r[off + i] = (byte) digits.charAt(i);
        int d = digits.charAt(len - 1) - '0';
        r[off + len - 1] = (byte) (value.signum() < 0 ? (d == 0 ? '}' : 'J' + d - 1) : (d == 0 ? '{' : 'A' + d - 1));
