# python tools/conformance/gen_parity23.py MlCpu/src/CobolConformance/corpus/parity/PARITY23.cbl
# Generates corpus/parity/PARITY23.cbl: a program past every JVM limit the emitter splits (more than 600 data items,
# 1,000 VALUE statements, 1,000 ProgramState fields and 1,000 paragraphs; a paragraph of more than 2,500 Java lines).
N_ITEMS, N_PARAS, N_WHEN = 2400, 1050, 160
L = []
def a(s): L.append(s)
a("       IDENTIFICATION DIVISION.")
a("       PROGRAM-ID. PARITY23.")
a("      * Generated by tools/conformance/gen_parity23.py. JVM limits")
a("      * of a large program: 2,400 data items with VALUE clauses, 1,050")
a("      * paragraphs and one paragraph of 160 WHENs whose Java passes 64 KB")
a("      * (GO TO, EXIT PARAGRAPH, NEXT SENTENCE and EXIT PERFORM in them).")
a("       DATA DIVISION.")
a("       WORKING-STORAGE SECTION.")
a("       01 WS-ITEMS.")
for i in range(1, N_ITEMS + 1):
    k = i % 3
    if k == 0:   a(f"          05 WS-I{i:04d}  PIC 9(4) VALUE {i % 997}.")
    elif k == 1: a(f"          05 WS-I{i:04d}  PIC S9(5) COMP-3 VALUE -{i % 89}.")
    else:        a(f"          05 WS-I{i:04d}  PIC X(3) VALUE 'A{i % 100:02d}'.")
a("       01 WS-SUM            PIC S9(9) VALUE 0.")
a("       01 WS-TXT            PIC X(40) VALUE SPACES.")
a("       01 WS-K              PIC 9(4) VALUE 0.")
a("       01 WS-J              PIC 9(4) VALUE 0.")
a("       01 WS-T              PIC S9(9) VALUE 0.")
a("       01 WS-U              PIC S9(9) COMP-3 VALUE 0.")
a("       PROCEDURE DIVISION.")
a("       MAIN-PARA.")
a(f"           PERFORM P0001 THRU P{N_PARAS:04d}")
a("           DISPLAY 'SUM ' WS-SUM ' TXT ' WS-TXT")
a(f"           PERFORM BIG-PARA THRU BIG-EXIT")
a(f"               VARYING WS-K FROM 1 BY 1 UNTIL WS-K > {N_WHEN + 2}")
a("           DISPLAY 'T ' WS-T ' U ' WS-U ' J ' WS-J")
a("           DISPLAY 'LAST ' WS-I2399 ' ' WS-I2400 ' ' WS-I0998")
a("           GOBACK.")
for i in range(1, N_PARAS + 1):
    a(f"       P{i:04d}.")
    k = i % 3
    if k == 0:   a(f"           ADD WS-I{i:04d} TO WS-SUM.")
    elif k == 1: a(f"           SUBTRACT WS-I{i:04d} FROM WS-SUM.")
    else:        a(f"           MOVE WS-I{i:04d} TO WS-TXT ({(i % 13) + 1}:3).")
a("       BIG-PARA.")
a("           EVALUATE WS-K")
for w in range(1, N_WHEN + 1):
    a(f"               WHEN {w}")
    a(f"                   ADD {w} TO WS-T ON SIZE ERROR MOVE 0 TO WS-T")
    a(f"                   END-ADD")
    a(f"                   COMPUTE WS-U = (WS-U + WS-K * {w} - WS-T) / 7")
    a(f"                   MOVE WS-I{w:04d} TO WS-TXT ({(w % 30) + 1}:3)")
    a(f"                   IF WS-T > {w * 5}")
    a(f"                       SUBTRACT 3 FROM WS-T")
    a(f"                   ELSE")
    a(f"                       ADD 2 TO WS-T")
    a(f"                   END-IF")
    a(f"                   MULTIPLY 2 BY WS-U ON SIZE ERROR MOVE 1 TO WS-U")
    a(f"                   END-MULTIPLY")
    a(f"                   DIVIDE 3 INTO WS-U")
    a(f"                   ADD WS-I{3 * w + 300:04d} TO WS-T")
    if w % 8 == 1:
        a(f"                   IF WS-T > 100 GO TO BIG-EXIT END-IF")
    if w % 8 == 3:
        a(f"                   IF WS-K = {w} EXIT PARAGRAPH END-IF")
    if w % 8 == 5:
        a(f"                   IF WS-K = {w} NEXT SENTENCE END-IF")
    if w % 8 == 7:
        a(f"                   PERFORM VARYING WS-J FROM 1 BY 1 UNTIL WS-J > 9")
        a(f"                       ADD 1 TO WS-U")
        a(f"                       IF WS-J = 4 EXIT PERFORM END-IF")
        a(f"                   END-PERFORM")
a("               WHEN OTHER")
a("                   ADD 1000 TO WS-T")
a("           END-EVALUATE")
a("           ADD 1 TO WS-U.")
a("       BIG-EXIT.")
a("           EXIT.")
import sys
open(sys.argv[1], "w", newline="\n").write("\n".join(L) + "\n")
print(len(L), "lines")
