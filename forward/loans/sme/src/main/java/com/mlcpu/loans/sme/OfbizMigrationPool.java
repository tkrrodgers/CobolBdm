package com.mlcpu.loans.sme;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.JsonNodeFactory;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.mlcpu.loans.acceptance.memory.InMemoryPorts;
import com.mlcpu.loans.api.legacy.LegacyCodec;
import com.mlcpu.loans.api.legacy.LegacyRecordException;
import com.mlcpu.loans.api.migration.LegacyLoan;
import com.mlcpu.loans.api.migration.LegacyTerms;
import com.mlcpu.loans.api.migration.Reconciliation;
import com.mlcpu.loans.api.migration.ReconciliationOutcome;
import com.mlcpu.loans.api.servicing.BookLoan;
import com.mlcpu.loans.api.servicing.Booked;
import com.mlcpu.loans.api.servicing.BookingOutcome;
import com.mlcpu.loans.api.servicing.BookingRejected;
import com.mlcpu.loans.api.servicing.LoanServicing;
import com.mlcpu.loans.application.LoansApplication;
import com.mlcpu.loans.migration.Migration;
import java.io.IOException;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * The host scenarios of the legacy book's migration (FE 9.2 LEG-02 to LEG-05; the plugin's migrateLegacyLoanBook, generated by
 * H-OFBIZ-MIGRATION): small legacy books copied into the host scenarios (host/scenarios/legacy/&lt;book&gt;, the five datasets
 * as the legacy job left them), one scenario per book that migrates it and checks every reconciliation row and the bookings,
 * one that migrates it again (idempotent: the same result, nothing new), and one with an SME-altered book that does not
 * reconcile (nothing is stored). Expected values: the reference's reconciliation, and booking over the in-memory ports with
 * the host scenarios' ledger (base currency USD, rates for EUR, INR, JPY, ZAR: the plugin's test data).
 *
 * <p>Usage: OfbizMigrationPool &lt;legacy-books.json&gt; &lt;CobolBdm root&gt; &lt;fineract-cobol-gen root&gt; &lt;host scenarios dir&gt;
 * &lt;plugin's scenarios dir, as OFBiz sees it from its root&gt; &lt;book&gt;...
 */
public final class OfbizMigrationPool {

    private static final ObjectMapper JSON = new ObjectMapper().enable(SerializationFeature.INDENT_OUTPUT);
    private static final JsonNodeFactory NODES = JsonNodeFactory.instance;
    private static final LocalDate TODAY = LocalDate.of(2026, 9, 1);
    private static final String OWNER = "LOAN_BORROWER_1";
    private static final String ORGANIZATION = "Company";
    private static final String PRODUCT = "LOAN_STD";
    private static final String[] DATASETS = {"LOAN.REQUEST.DATA", "RUN.CONTROL", "CURRENCY.VSAM.KSDS", "LOAN.SCHEDULE.DATA", "LOAN.REJECTS.DATA"};

    public static void main(String[] args) throws IOException {
        JsonNode books = new ObjectMapper().readTree(Path.of(args[0]).toFile());
        Map<String, Path> roots = Map.of("cobolbdm", Path.of(args[1]), "fcg", Path.of(args[2]));
        Path out = Path.of(args[3]);
        String pluginScenarios = args[4];
        List<String> problems = new ArrayList<>();
        Path legacyDir = out.resolve("legacy");
        Path scenarioDir = out.resolve("migration");
        Files.createDirectories(scenarioDir);
        int n = 0;
        for (int i = 5; i < args.length; i++) {
            String name = args[i];
            JsonNode b = null;
            for (JsonNode x : books.get("books")) if (x.get("name").asText().equals(name)) b = x;
            if (b == null) throw new IllegalArgumentException("no book " + name);
            MigrationPool.Book book = MigrationPool.read(b, roots, problems);
            Path bookDir = legacyDir.resolve(name);
            Files.createDirectories(bookDir);
            String[] roles = {"request", "runControl", "currency", "schedule", "rejects"};
            for (int k = 0; k < roles.length; k++) {
                JsonNode d = b.get(roles[k]);
                byte[] bytes = Files.readAllBytes(roots.get(d.get("root").asText()).resolve(d.get("path").asText()));
                if ("lines".equals(d.get("format").asText())) {
                    int length = switch (roles[k]) {
                        case "request" -> LegacyCodec.REQUEST_LENGTH;
                        case "runControl" -> LegacyCodec.RUN_CONTROL_LENGTH;
                        default -> LegacyCodec.CURRENCY_LENGTH;
                    };
                    bytes = String.join("", LegacyCodec.lines(new String(bytes, LegacyCodec.CHARSET), length)).getBytes(LegacyCodec.CHARSET);
                }
                Files.write(bookDir.resolve(DATASETS[k]), bytes);
            }
            String dir = pluginScenarios + "/legacy/" + name;
            String id = String.format("ofb-m%03d", ++n);
            write(scenarioDir, id, migrate(id, "M-" + name, dir, book, "the legacy book " + name + " migrated", problems));
            id = String.format("ofb-m%03d", ++n);
            ObjectNode again = migrate(id, "M-" + name + "-2", dir, book, "the legacy book " + name + " migrated twice (LEG-05: the second run returns the first's result)",
                    problems);
            ArrayNode steps = (ArrayNode) again.get("steps");
            steps.add(steps.get(0).deepCopy());
            write(scenarioDir, id, again);
        }
        // a book that does not reconcile: the first sample cell with one installment's interest a hundredth higher in the legacy
        String name = args.length > 5 ? args[5] : null;
        if (name != null) {
            JsonNode b = null;
            for (JsonNode x : books.get("books")) if (x.get("name").asText().equals(name)) b = x;
            MigrationPool.Book book = MigrationPool.read(b, roots, problems);
            Path bookDir = legacyDir.resolve(name + "-altered");
            Files.createDirectories(bookDir);
            for (String ds : DATASETS) Files.copy(legacyDir.resolve(name).resolve(ds), bookDir.resolve(ds), java.nio.file.StandardCopyOption.REPLACE_EXISTING);
            byte[] sched = Files.readAllBytes(bookDir.resolve("LOAN.SCHEDULE.DATA"));
            int at = -1;
            for (int r = 0; r < sched.length; r += LegacyCodec.SCHEDULE_RECORD_LENGTH) {
                if (sched[r + 16] == 'R') {
                    at = r;
                    break;
                }
            }
            String rec = new String(sched, at, LegacyCodec.SCHEDULE_RECORD_LENGTH, LegacyCodec.CHARSET);
            BigDecimal interest = LegacyCodec.scheduleLine(rec).interest().add(new BigDecimal("0.01"));
            String digits = interest.abs().movePointRight(4).setScale(0).toPlainString();
            String altered = rec.substring(0, 59) + (interest.signum() < 0 ? "-" : "+") + "0".repeat(17 - digits.length()) + digits + rec.substring(77);
            System.arraycopy(altered.getBytes(LegacyCodec.CHARSET), 0, sched, at, LegacyCodec.SCHEDULE_RECORD_LENGTH);
            Files.write(bookDir.resolve("LOAN.SCHEDULE.DATA"), sched);
            String id = String.format("ofb-m%03d", ++n);
            ObjectNode sc = NODES.objectNode();
            sc.put("schema", "mlcpu.ofbiz-scenario.v1");
            sc.put("id", id);
            sc.put("origin", "the legacy book " + name + " with one installment's interest altered: it does not reconcile, nothing is migrated (LEG-03, LEG-05)");
            sc.putArray("rules").add("LEG-03").add("LEG-05");
            ObjectNode step = sc.putArray("steps").addObject();
            step.put("service", "migrateLegacyLoanBook");
            step.put("today", TODAY.toString());
            step.set("params", params("M-" + name + "-altered", pluginScenarios + "/legacy/" + name + "-altered", "L" + id.substring(4) + "-"));
            step.putObject("expect").put("success", false).put("errorContains", "does not reconcile");
            ObjectNode c = OfbizPool.check("LoanLegacyRecon", OfbizPool.where("migrationId", "M-" + name + "-altered"), List.of(), NODES.arrayNode());
            c.remove("rows");
            c.remove("fields");
            c.put("count", 0);
            sc.putArray("checks").add(c);
            write(scenarioDir, id, sc);
        }
        System.out.printf("ofbiz migration pool: %d scenarios, %d problem(s)%n", n, problems.size());
        problems.forEach(p -> System.out.println("  problem: " + p));
        if (!problems.isEmpty()) System.exit(1);
    }

    private static ObjectNode params(String migrationId, String bookDir, String prefix) {
        ObjectNode p = NODES.objectNode();
        p.put("migrationId", migrationId);
        p.put("externalIdPrefix", prefix);
        p.put("bookDir", bookDir);
        p.put("ownerPartyId", OWNER);
        p.put("organizationPartyId", ORGANIZATION);
        p.put("loanProductId", PRODUCT);
        p.put("businessDate", TODAY.toString());
        return p;
    }

    /** One migration of a book: the run's result, every reconciliation row, the number of legacy lines stored. */
    private static ObjectNode migrate(String id, String migrationId, String bookDir, MigrationPool.Book book, String origin, List<String> problems) {
        // the loans of each scenario under their own external ids (the harness retires a scenario's loans after it)
        String prefix = "L" + id.substring(4) + "-";
        Migration migration = new Migration(LoansApplication.quotes());
        InMemoryPorts memory = new InMemoryPorts(new InMemoryPorts.Given(TODAY, "USD", OfbizPool.RATES));
        LoanServicing servicing = LoansApplication.create(memory.ports());
        Map<String, Integer> outcomes = new TreeMap<>();
        ArrayNode rows = NODES.arrayNode();
        int booked = 0;
        int notBookable = 0;
        int lines = 0;
        for (String raw : book.requests()) {
            String legacyLoanId = raw.substring(2, 18);
            ObjectNode row = NODES.objectNode();
            row.put("legacyLoanId", legacyLoanId);
            LegacyLoan loan;
            try {
                loan = MigrationPool.loan(input(book, raw));
            } catch (LegacyRecordException e) {
                row.put("outcome", "UNDECODABLE").put("decision", "D-5").put("field", e.field());
                row.putNull("legacyCode").putNull("serviceRejection").putNull("loanId").putNull("bookingRejection");
                rows.add(row);
                outcomes.merge("UNDECODABLE D-5", 1, Integer::sum);
                continue;
            }
            Reconciliation r = migration.reconcile(loan);
            if (r.outcome() == ReconciliationOutcome.DIFF) problems.add(origin + ": loan " + legacyLoanId + " differs: " + r);
            outcomes.merge(r.outcome().name() + (r.decision() == null ? "" : " " + r.decision()), 1, Integer::sum);
            row.put("outcome", r.outcome().name());
            row.put("decision", r.decision());
            row.put("field", r.field());
            row.put("legacyCode", r.legacyCode());
            row.put("serviceRejection", r.serviceRejection() == null ? null : r.serviceRejection().name());
            String loanId = null;
            String bookingRejection = null;
            if (loan.header() != null && (r.outcome() == ReconciliationOutcome.MATCH || "D-2".equals(r.decision()))
                    && migration.terms(loan) instanceof LegacyTerms t) {
                BookingOutcome o = servicing.book(new BookLoan(prefix + legacyLoanId, OWNER, ORGANIZATION, PRODUCT, t.terms()));
                if (o instanceof Booked b) {
                    loanId = b.loanId();
                    booked++;
                } else if (o instanceof BookingRejected br) {
                    bookingRejection = br.reason().name();
                    notBookable++;
                }
            }
            row.put("loanId", loanId);
            row.put("bookingRejection", bookingRejection);
            rows.add(row);
            if (loan.header() != null) lines += loan.lines().size();
        }
        ObjectNode sc = NODES.objectNode();
        sc.put("schema", "mlcpu.ofbiz-scenario.v1");
        sc.put("id", id);
        sc.put("origin", origin + "; expected values: the reference's reconciliation, booking over in-memory ports with the host ledger");
        sc.putArray("rules").add("LEG-02").add("LEG-03").add("LEG-04").add("LEG-05");
        ObjectNode step = sc.putArray("steps").addObject();
        step.put("service", "migrateLegacyLoanBook");
        step.put("today", TODAY.toString());
        step.set("params", params(migrationId, bookDir, prefix));
        ObjectNode expect = step.putObject("expect");
        expect.put("outcome", "MigrationRun");
        ObjectNode result = expect.putObject("result");
        result.put("migrationId", migrationId);
        result.put("loans", book.requests().size());
        ObjectNode o = result.putObject("outcomes");
        outcomes.forEach(o::put);
        result.put("booked", booked);
        result.put("notBookable", notBookable);
        ArrayNode checks = sc.putArray("checks");
        checks.add(OfbizPool.check("LoanLegacyRecon", OfbizPool.where("migrationId", migrationId), List.of("legacyLoanId"), rows));
        ObjectNode count = OfbizPool.check("LoanLegacyLine", OfbizPool.where("migrationId", migrationId), List.of(), NODES.arrayNode());
        count.remove("rows");
        count.remove("fields");
        count.put("count", lines);
        checks.add(count);
        return sc;
    }

    private static ObjectNode input(MigrationPool.Book book, String request) {
        ObjectNode in = NODES.objectNode();
        String loanId = request.substring(2, 18);
        in.put("request", request);
        in.put("runControl", book.runControl());
        String currency = book.currencies().get(request.substring(26, 29));
        if (currency == null) in.putNull("currency");
        else in.put("currency", currency);
        ArrayNode s = in.putArray("schedule");
        book.schedules().getOrDefault(loanId, List.of()).forEach(s::add);
        String reject = book.rejects().get(loanId);
        if (reject == null) in.putNull("reject");
        else in.put("reject", reject);
        return in;
    }

    private static void write(Path dir, String id, ObjectNode sc) throws IOException {
        Files.writeString(dir.resolve(id + ".json"), JSON.writeValueAsString(sc) + "\n", StandardCharsets.UTF_8);
    }
}
