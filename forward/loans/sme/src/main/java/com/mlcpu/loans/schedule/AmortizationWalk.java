/**
 * GENERATED by sme/tools/make_schedule_walk.py from the reference's Amortization: do not edit.
 * The amortization schedule of a declining-balance loan (rules AMZ and PLAN): the disbursement, the equal installment, the last
 * installment's settlement, the evening-out of the installments, and the schedule's lines and totals.
 * The calendar and the rate factors come through the SPIs.
 */
public final class AmortizationWalk {

    private final DueDates dueDates;
    private final RateFactors rates;

    public AmortizationWalk(DueDates dueDates, RateFactors rates) {
        this.dueDates = dueDates;
        this.rates = rates;
    }

    /** The schedule of admissible terms; {@code downPayment} is the terms' down payment, null when they have none. */
    public ScheduleOutcome schedule(ScheduleRequest request, Money downPayment) {
        return new Run(request, rates).schedule(dueDates.periods(request), downPayment);
    }

    /** One loan's calculation. */
    private static final class Run {

        private final ScheduleRequest q;
        private final RateFactors rates;

        Run(ScheduleRequest q, RateFactors rates) {
            this.q = q;
            this.rates = rates;
        }

        ScheduleOutcome schedule(List<Period> calendar, Money downPayment) {
            MathContext mc = new MathContext(q.calculation().precision(), q.calculation().roundingMode());
            int decimals = q.currency().decimalPlaces();
            Money zero = Money.zero(decimals, mc);
            Money principal = zero.of(q.principal());
            Plan plan = Plan.of(calendar, zero);
            Walk.periods(q, plan);

            List<ScheduleLine> lines = new ArrayList<>();
            List<Money[]> installments = new ArrayList<>();
            List<Integer> numbers = new ArrayList<>();
            Money toBeScheduled = zero;
            Money cumulativePrincipal = zero;
            Money cumulativeInterest = zero;
            Money repaymentExpected = zero;
            boolean disbursed = false;
            int number = 1;
            LocalDate d = q.disbursementDate();
            for (int k = 0; k < calendar.size(); k++) {
                Period period = calendar.get(k);
                if (!disbursed && !d.isBefore(period.from()) && d.isBefore(period.due())) {
                    disbursed = true;
                    Step before = balanceBefore(plan, d);
                    if (before.stopped()) {
                        return Walk.rejected("rating the plan cut at the disbursement date (AMZ-03)", rejected(before.rejection()));
                    }
                    Money balanceBefore = before.plan().figures(before.plan().find(d)).balance();
                    Walk.disbursement(d, plan.find(d), principal, balanceBefore);
                    Money amount = zero.of(principal.amount());
                    lines.add(new DisbursementLine(d, d, amount.amount(), amount.amount()));
                    Money dp = zero;
                    if (q.downPaymentEnabled()) {
                        dp = downPayment;
                        Walk.downPayment(dp);
                        lines.add(new DownPaymentLine(number, d, d, dp.amount(), dp.amount(), balanceBefore.plus(amount).minus(dp).amount(), null));
                        repaymentExpected = repaymentExpected.plus(dp);
                        number++;
                    }
                    Money remaining = amount.minus(dp);
                    toBeScheduled = toBeScheduled.plus(remaining);
                    Step s = disburse(plan, d, remaining);
                    if (s.stopped()) {
                        return Walk.rejected("disbursing and computing the installments", rejected(s.rejection()));
                    }
                    plan = s.plan();
                }
                Figures f = plan.figures(k);
                Money principalDue = f.duePrincipal();
                Money interestDue = f.dueInterest();
                cumulativePrincipal = cumulativePrincipal.plus(principalDue);
                cumulativeInterest = cumulativeInterest.plus(interestDue);
                repaymentExpected = repaymentExpected.plus(principalDue.plus(interestDue));
                installments.add(new Money[] { principalDue, interestDue, zero.plus(principalDue).plus(interestDue), f.balance() });
                numbers.add(number);
                lines.add(null);
                number++;
            }
            if (!disbursed) {
                // D-3: a disbursement outside the term leaves nothing to schedule
                return Walk.rejected("looking for the period of the disbursement date (AMZ-02)", rejected(ScheduleRejection.DISBURSEMENT_OUTSIDE_TERM));
            }

            // the lines with the total still outstanding after each
            BigDecimal outstanding = repaymentExpected.amount();
            List<ScheduleLine> out = new ArrayList<>(lines.size());
            int k = 0;
            for (ScheduleLine line : lines) {
                if (line instanceof DownPaymentLine p) {
                    outstanding = outstanding.subtract(p.principal());
                    out.add(new DownPaymentLine(p.number(), p.from(), p.due(), p.principal(), p.totalDue(), p.balanceAfter(), outstanding));
                } else if (line == null) {
                    Money[] a = installments.get(k);
                    Period period = calendar.get(k);
                    int no = numbers.get(k);
                    k++;
                    outstanding = outstanding.subtract(a[2].amount());
                    out.add(new InstallmentLine(no, period.from(), period.due(), a[0].amount(), a[1].amount(), zero.amount(), zero.amount(),
                            a[2].amount(), a[3].amount(), outstanding));
                } else {
                    out.add(line);
                }
            }
            Money dpTotal = downPayment != null ? downPayment : zero;
            Totals totals = new Totals(toBeScheduled.plus(dpTotal).amount(), cumulativePrincipal.plus(dpTotal).amount(),
                    cumulativeInterest.amount(), zero.amount(), zero.amount(), repaymentExpected.amount(), zero.amount());
            return new Scheduled(new Schedule(q.loanId(), q.currency().code(), decimals, plan.termDays(), totals, List.copyOf(out)));
        }

        private Rejected rejected(ScheduleRejection reason) {
            return new Rejected(q.loanId(), reason, null);
        }

        // ------------------------------------------------------------------ the disbursement

        /**
         * The balance outstanding on a date, before a disbursement on it: the plan recalculated to that date (its stretches cut at
         * the date, the later periods emptied). The recalculation rates the stretches, so terms whose rate factors cannot be
         * computed are rejected here, before anything else about the disbursement.
         */
        private Step balanceBefore(Plan plan, LocalDate date) {
            Walk.on(false);
            if (date.isBefore(plan.at(0).from()) || !date.isBefore(plan.at(plan.size() - 1).due())) {
                throw new IllegalStateException("a disbursement is processed only inside a period: " + date);
            }
            int at = plan.find(date);
            Plan cut = plan.map((i, p) -> {
                if (!p.due().isAfter(date)) {
                    return p;
                }
                if (i == at) {
                    int j = plan.findStretch(i, date);
                    if (j < 0) {
                        return p;
                    }
                    List<Stretch> kept = new ArrayList<>(p.stretches().subList(0, j + 1));
                    kept.set(j, kept.get(j).withDue(date));
                    return p.withStretches(kept);
                }
                return p.stretches().isEmpty() ? p : p.withStretches(List.of());
            });
            Step s = rate(cut, cut.all());
            if (s.stopped()) {
                return s;
            }
            s = s.plan().rollBalances();
            if (s.stopped()) {
                return s;
            }
            return settleLast(s.plan(), date);
        }

        /** Disburses the amount on the date and computes the installments of the periods it affects. */
        private Step disburse(Plan plan, LocalDate date, Money amount) {
            Walk.on(true);
            if (q.fullTermTranche() && q.installments() > 0) {
                // D-1: the legacy calculation stopped on a full-term tranche
                return Step.stop(ScheduleRejection.FULL_TERM_TRANCHE_NOT_OFFERED);
            }
            int i = plan.find(date);
            if (i < 0) {
                return Step.to(plan);
            }
            plan = plan.disburse(i, date, amount);
            LocalDate dueFrom = plan.at(i).due();
            if (plan.at(i).due().isEqual(date) && i + 1 < plan.size()) {
                dueFrom = plan.at(i + 1).due();
            }
            if (q.interestMethod() == InterestMethod.FLAT) {
                Step rated = rate(plan, plan.dueFrom(dueFrom));
                // D-1: the legacy calculation stopped on flat interest, once the rate factors were computed
                return rated.stopped() ? rated : Step.stop(ScheduleRejection.FLAT_INTEREST_NOT_OFFERED);
            }
            return decliningBalance(plan, dueFrom);
        }

        private Step decliningBalance(Plan plan, LocalDate dueFrom) {
            List<Integer> related = plan.dueFrom(dueFrom);
            boolean first = plan.hasNoInstallments();
            Step s = rate(plan, related);
            Walk.factors(s, related);
            if (s.stopped()) {
                return s;
            }
            s = s.plan().rollBalances();
            if (s.stopped()) {
                return s;
            }
            if (!first) {
                throw new IllegalStateException("only the first disbursement is supported");
            }
            s = Walk.figures("After the installment, the balances rolled (AMZ-08, AMZ-09)", installment(s.plan(), related).rollBalances());
            if (s.stopped()) {
                return s;
            }
            s = Walk.figures("After the settlement (AMZ-12)", settleLast(s.plan(), dueFrom));
            if (s.stopped() || related.isEmpty()) {
                return s;
            }
            return Walk.figures("After the evening-out (AMZ-13)", evenOut(s.plan(), related));
        }

        // ------------------------------------------------------------------ rate factors

        /** The plan with the stretches of the given periods rated through the RateFactors SPI. */
        private Step rate(Plan plan, List<Integer> periods) {
            Map<Integer, List<Factors>> factors = new HashMap<>();
            for (int i : periods) {
                Installment p = plan.at(i);
                Period period = new Period(p.from(), p.due());
                List<Factors> f = new ArrayList<>(p.stretches().size());
                for (Stretch s : p.stretches()) {
                    RateOutcome r = rates.factors(new RateQuery(q.scheduleStart(), period, s.from(), s.due(), q.annualRatePercent(),
                            q.frequency(), q.every(), q.monthDays(), q.yearDays()), q.calculation());
                    if (r instanceof RateRejected rejected) {
                        return Step.stop(rejected.reason());
                    }
                    f.add((Factors) r);
                }
                factors.put(i, f);
            }
            return Step.to(plan.withFactors(factors));
        }

        // ------------------------------------------------------------------ the installment

        /**
         * The equal installment of the related periods: the balance it amortizes times the product of their growth factors, over
         * 1 + g(n) + g(n) g(n-1) + ... (the annuity of the periods' factors), at the currency's decimal places. A negative
         * installment is not set.
         */
        private static Plan installment(Plan plan, List<Integer> related) {
            if (related.isEmpty()) {
                return plan;
            }
            MathContext mc = plan.zero().mathContext();
            BigDecimal product = BigDecimal.ONE;
            for (int i : related) {
                product = product.multiply(plan.figures(i).growth(), mc);
            }
            BigDecimal annuity = BigDecimal.ONE;
            for (int i : related.subList(1, related.size())) {
                annuity = BigDecimal.ONE.add(annuity.multiply(plan.figures(i).growth(), mc), mc);
            }
            product = strip(product);
            annuity = strip(annuity);
            Money balance = plan.balanceForInstallment(related.get(0));
            Money amount = balance.of(product.multiply(balance.amount(), mc).divide(annuity, mc));
            Walk.installment(related, balance, product, annuity, amount);
            if (amount.isNegative()) {
                return plan;
            }
            Set<Integer> in = new HashSet<>(related);
            return plan.map((i, p) -> in.contains(i) ? p.withInstallment(amount) : p);
        }

        private static BigDecimal strip(BigDecimal v) {
            return new BigDecimal(v.stripTrailingZeros().toPlainString());
        }

        /**
         * The last unsettled installment takes the rounding difference: what was disbursed plus all interest due, less all
         * installments. If that makes it negative it becomes zero, and the one before it takes the difference.
         */
        private Step settleLast(Plan plan, LocalDate tillDate) {
            Money zero = plan.zero();
            Money disbursed = plan.disbursed();
            for (int i = 0; i < plan.size(); i++) {
                if (Money.positiveOrZero(plan.figures(i).duePrincipal()).exceeds(disbursed)) {
                    // D-1: the legacy calculation stopped when one installment was to carry more principal than the loan has
                    return Step.stop(ScheduleRejection.SINGLE_INSTALLMENT_AFTER_LATE_DISBURSEMENT);
                }
            }
            int found = -1;
            for (int i = 0; i < plan.size(); i++) {
                if (!plan.at(i).isSettled()) {
                    found = i;
                }
            }
            if (found < 0) {
                int n = plan.size() - 1;
                if (!plan.at(n).stretches().isEmpty() && plan.figures(n).balance().isPositive()) {
                    found = n;
                }
            }
            if (found < 0) {
                return Step.to(plan);
            }
            int last = found;
            Money totalDueInterest = zero;
            Money totalPayable = zero;
            Money totalDisbursed = zero;
            for (int i = 0; i < plan.size(); i++) {
                totalDueInterest = totalDueInterest.plus(plan.figures(i).dueInterest());
            }
            for (int i = 0; i < plan.size(); i++) {
                totalPayable = totalPayable.plus(plan.at(i).payable());
            }
            for (int i = 0; i < plan.size(); i++) {
                for (Stretch s : plan.at(i).stretches()) {
                    totalDisbursed = totalDisbursed.plus(s.disbursement());
                }
            }
            Money difference = totalDisbursed.plus(totalDueInterest).minus(totalPayable);
            Walk.settlement(last, totalDisbursed, totalDueInterest, totalPayable, difference);
            plan = plan.with(last, plan.at(last).withInstallment(plan.at(last).installment().plus(difference)));
            if (plan.at(last).installment().isNegative()) {
                Step s = settleLast(plan.with(last, plan.at(last).withInstallment(zero)), tillDate);
                if (s.stopped()) {
                    return s;
                }
                plan = s.plan();
            }
            return Step.to(plan);
        }

        /**
         * Evens out the installments when the last one differs from the one before by more than the tolerance: the difference is
         * spread over the periods, at most three rounds, as long as each round narrows it.
         */
        private Step evenOut(Plan plan, List<Integer> related) {
            Plan trial = null;
            int round = 1;
            do {
                InstallmentSpread spread = InstallmentSpread.of(plan, related);
                Walk.spread(round, spread);
                if (!spread.isWorthSpreading()) {
                    break;
                }
                Money spreadAmount = spread.spread();
                if (spreadAmount.sameAs(spread.base())) {
                    break;
                }
                if (trial == null) {
                    trial = plan;
                }
                LocalDate firstFrom = plan.at(related.get(0)).from();
                LocalDate firstDue = plan.at(related.get(0)).due();
                if (!spreadAmount.isNegative()) {
                    trial = trial.map((i, p) -> inRun(p, firstFrom, firstDue) ? p.withInstallment(spreadAmount) : p);
                }
                Step s = trial.rollBalances();
                if (s.stopped()) {
                    return s;
                }
                s = settleLast(s.plan(), firstDue);
                if (s.stopped()) {
                    return s;
                }
                trial = s.plan();
                if (!InstallmentSpread.of(trial, trial.all()).isNarrowerThan(spread)) {
                    break;
                }
                List<Money> fromTrial = new ArrayList<>();
                for (int i = 0; i < trial.size(); i++) {
                    if (inRun(trial.at(i), firstFrom, firstDue)) {
                        fromTrial.add(trial.at(i).installment());
                    }
                }
                Map<Integer, Money> taken = new HashMap<>();
                for (int k = 0; k < related.size() && k < fromTrial.size(); k++) {
                    taken.put(related.get(k), fromTrial.get(k));
                }
                s = plan.map((i, p) -> taken.containsKey(i) ? p.withInstallment(taken.get(i)) : p).rollBalances();
                if (s.stopped()) {
                    return s;
                }
                plan = s.plan();
                round++;
            } while (round <= 3);
            return Step.to(plan);
        }

        private static boolean inRun(Installment p, LocalDate firstFrom, LocalDate firstDue) {
            return !p.from().isBefore(firstFrom) && !p.due().isBefore(firstDue);
        }
    }
}
