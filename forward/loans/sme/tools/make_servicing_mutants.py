    ("AccountTransactionType.WITHDRAWAL, d.amount(), d.due(), paymentId,", f"AccountTransactionType.WITHDRAWAL, d.amount(), {M}SRV_04 ? ports.clock().today() : d.due(), paymentId,"),
    ("            return new ServicingRejected(command.loanId(), ServicingRejection.UNKNOWN_LOAN);",
     f"            return new ServicingRejected(command.loanId(), {M}SRV_05 ? ServicingRejection.UNKNOWN_INVOICE : ServicingRejection.UNKNOWN_LOAN);"),
