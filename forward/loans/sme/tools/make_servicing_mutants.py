    ("            return new ServicingRejected(event.invoiceId(), ServicingRejection.UNKNOWN_INVOICE);",
     f"            return new ServicingRejected(event.invoiceId(), {M}SRV_10 ? ServicingRejection.UNKNOWN_LOAN : ServicingRejection.UNKNOWN_INVOICE);"),
