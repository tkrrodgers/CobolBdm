def main(src, out):
    s = open(src, encoding="utf-8").read().replace("\r\n", "\n")
    for a, b in EDITS:
        n = s.count(a)
        if n != 1:
            raise SystemExit(f"snippet found {n} times (want 1): {a[:90]!r}")
        s = s.replace(a, b)
    head = "// GENERATED by sme/tools/make_servicing_mutants.py from the reference's Servicing: do not edit.\n"
    open(os.path.join(out, "ServicingM.java"), "w", encoding="utf-8", newline="\n").write(head + s)
    enum = ("// GENERATED by sme/tools/make_servicing_mutants.py: do not edit.\npackage com.mlcpu.loans.application;\n\n"
            "/** The servicing rule mutants; M is the one in force on this thread (null: none). */\n"
            "public enum ServicingMutant {\n" + ",\n".join(f'    {n}("{d}")' for n, d in MUTANTS) + ";\n\n"
            "    public static final ThreadLocal<ServicingMutant> M = new ThreadLocal<>();\n\n"
            "    public final String change;\n\n    ServicingMutant(String change) {\n        this.change = change;\n    }\n\n"
            "    public String rule() {\n        return name().replace('_', '-');\n    }\n}\n")
    open(os.path.join(out, "ServicingMutant.java"), "w", encoding="utf-8", newline="\n").write(enum)
    print(f"{len(MUTANTS)} mutants written to {out}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
