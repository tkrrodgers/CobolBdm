def main(src, out):
    s = open(src, encoding="utf-8").read().replace("\r\n", "\n")
    for a, b in EDITS:
        n = s.count(a)
        if n != 1:
            raise SystemExit(f"snippet found {n} times (want 1): {a[:90]!r}")
        s = s.replace(a, b)
    s = s.replace("/**\n * The amortization schedule", "/**\n * GENERATED by sme/tools/make_schedule_walk.py from the reference's Amortization: do not edit.\n * The amortization schedule", 1)
    open(out, "w", encoding="utf-8", newline="\n").write(s)
    print(f"{len(EDITS)} walk points written to {out}")


