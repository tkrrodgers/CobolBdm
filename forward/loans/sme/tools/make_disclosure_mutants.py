"""Generates the disclosure context's rule mutants (ForwardEngineeringFineract.md section 7.2, step 3: one mutant per digest rule)
from the reference's ScheduleDocuments, UnitPeriod and CostOfCredit: copies named ...M in the SME project
(sme/src/main/java/com/mlcpu/loans/disclosure), each mutation one snippet of the reference that must occur exactly once, so the
mutants follow the reference when it changes: run this again. The mutant in force is DisclosureMutant.M (one per thread: the
pools evaluate candidates in parallel). RPT-05 and DISC-07 (a rejection passed through) are mutated in DisclosurePool.

Usage: python -I make_disclosure_mutants.py <reference loans-disclosure java dir> <out dir>
"""
import os, sys

MUTANTS = [
    ("RPT_01", "periods counts the installment lines only"),
    ("RPT_02", "the disbursement line is number 1"),
    ("RPT_03", "an installment line's outstanding is its remainingDue"),
    ("RPT_04", "the total interest is the totals' fee"),
    ("RPT_05", "a rejection is passed on with a field"),
    ("DISC_01", "the amount financed ignores the down payment"),
    ("DISC_02", "the total of payments sums the principal"),
    ("DISC_03", "the finance charge is taken from the disbursed amount"),
    ("DISC_04", "the fraction of a unit-period is ignored"),
    ("DISC_05", "the APR is rounded down"),
    ("DISC_06", "a zero finance charge gives an APR of 0 without decimals"),
    ("DISC_07", "a rejection is passed on with a field"),
    ("DISC_08", "the unit-period is the first period"),
    ("DISC_09", "a monthly fraction is days / 31"),
]

GET = "DisclosureMutant.M.get() == DisclosureMutant."

EDITS = {
    "ScheduleDocuments.java": [
        ("public final class ScheduleDocuments {", "public final class ScheduleDocumentsM {"),
        ("s.termDays(), lines.size(), lines,",
         f"s.termDays(), {GET}RPT_01 ? (int) lines.stream().filter(x -> x.type() == LineType.INSTALLMENT).count() : lines.size(), lines,"),
        ("new DocumentLine(LineType.DISBURSEMENT, 0,", f"new DocumentLine(LineType.DISBURSEMENT, {GET}RPT_02 ? 1 : 0,"),
        ("i.totalDue(), i.balanceAfter());", f"i.totalDue(), {GET}RPT_03 ? i.remainingDue() : i.balanceAfter());"),
        ("t.principal(), t.interest(),", f"t.principal(), {GET}RPT_04 ? t.fee() : t.interest(),"),
    ],
    "UnitPeriod.java": [
        ("        Measure common = counts.entrySet()", f"        Measure common = {GET}DISC_08 ? periods.get(0) : counts.entrySet()"),
        ("return new Count((int) k, BigDecimal.valueOf(d).divide(BigDecimal.valueOf(30), MC));",
         f"return new Count((int) k, BigDecimal.valueOf(d).divide(BigDecimal.valueOf({GET}DISC_09 ? 31 : 30), MC));"),
    ],
    "CostOfCredit.java": [
        ("public final class CostOfCredit {", "public final class CostOfCreditM {"),
        ("        BigDecimal financed = principal.subtract(down);", f"        BigDecimal financed = {GET}DISC_01 ? principal : principal.subtract(down);"),
        ("                total = total.add(i.totalDue());", f"                total = total.add({GET}DISC_02 ? i.principal() : i.totalDue());"),
        ("        BigDecimal charge = total.subtract(financed);", f"        BigDecimal charge = total.subtract({GET}DISC_03 ? principal : financed);"),
        ("BigDecimal.ONE.add(c.f().multiply(i, MC), MC)", f"BigDecimal.ONE.add(({GET}DISC_04 ? BigDecimal.ZERO : c.f()).multiply(i, MC), MC)"),
        ("        return BigDecimal.valueOf(hi, 2);", f"        return BigDecimal.valueOf({GET}DISC_05 ? lo : hi, 2);"),
        # a mutant may leave the present value above the amount financed at any rate (DISC-04's: a payment within the first
        # unit-period then counts in full): the copies give up at 10^9 percent instead of doubling forever
        ("            lo = hi;\n            hi *= 2;",
         "            lo = hi;\n            hi *= 2;\n            if (hi > 100_000_000_000L) {\n                return BigDecimal.valueOf(-1);\n            }"),
        ("charge.signum() <= 0 ? BigDecimal.ZERO.setScale(2)", f"charge.signum() <= 0 ? BigDecimal.ZERO.setScale({GET}DISC_06 ? 0 : 2)"),
    ],
}


def main(src, out):
    os.makedirs(out, exist_ok=True)
    head = "// GENERATED by sme/tools/make_disclosure_mutants.py from the reference's {0}: do not edit.\n"
    for name, edits in EDITS.items():
        s = open(os.path.join(src, name), encoding="utf-8").read().replace("\r\n", "\n")
        for a, b in edits:
            n = s.count(a)
            if n != 1:
                raise SystemExit(f"{name}: snippet found {n} times (want 1): {a[:90]!r}")
            s = s.replace(a, b)
        s = s.replace("UnitPeriod", "UnitPeriodM").replace("UnitPeriodMM", "UnitPeriodM")
        target = name.replace(".java", "M.java")
        open(os.path.join(out, target), "w", encoding="utf-8", newline="\n").write(head.format(name) + s)
    enum = ("// GENERATED by sme/tools/make_disclosure_mutants.py: do not edit.\npackage com.mlcpu.loans.disclosure;\n\n"
            "/** The disclosure context's rule mutants; M is the one in force on this thread (null: none). */\n"
            "public enum DisclosureMutant {\n" + ",\n".join(f'    {n}("{d}")' for n, d in MUTANTS) + ";\n\n"
            "    public static final ThreadLocal<DisclosureMutant> M = new ThreadLocal<>();\n\n"
            "    public final String change;\n\n    DisclosureMutant(String change) {\n        this.change = change;\n    }\n\n"
            "    public String rule() {\n        return name().replace('_', '-');\n    }\n}\n")
    open(os.path.join(out, "DisclosureMutant.java"), "w", encoding="utf-8", newline="\n").write(enum)
    print(f"{len(MUTANTS)} mutants written to {out}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
